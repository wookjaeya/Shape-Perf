#!/usr/bin/env python3
"""candidates.py -- the candidate list of unverified entries of the two C1 plans (judgement rules 8.13 item 3, format
plan/c1_closure_explain_rev4_spec_20261118.md 4.1; results 25.10), and the admission files of item 4: D2 (every line)
and D2[<kinds>] for every subset of the kinds that is neither empty nor whole.  Generated by rule; no line is chosen
by hand.  Run with python3 -I.

    candidates.py --out DIR --kairos KAIROS_DIR --kzdump KZ_DUMP  PLAN_DIR:RELATIONS_TXT:FACTS_KZ ...

Rule:
  rows         the sidecar's row lines the plan holds (state=planned or control-state=planned), paths A and B
  named        every entry a row's block of the relations text names in P0-unverified(<f>, ...) (layer P0, function f)
               or sem-unverified(<api>:<column>, ...) (layer framework); and every library call the row's sidecar
               namespace-entry line names in compare-call=, copy-call=, length-call=, fill-call= (layer P0)
  unverified   the facts' SEMANTICS records (kz-dump of the facts the plan was generated from) of that layer and
               function whose verify= is "unverified"; one line per (layer, function, column); a named entry with no
               such record is not a candidate (it is not unverified)
  data         P0: kairos/lib/llvm/p0.cpp (the P0 table the extraction compiles in), the line that defines the entry;
               framework: the semantics data file the SEMANTICS record names in its source text, the line "api <f> ..."
  kind         P0: the family the P0 table gives the entry (P0_TABLE family=, or the comparison table's family for a
               comparison entry), spaces written as "-"; framework: framework:<column>
  named_by     the kinds of lines that named it, joined by commas (P0-unverified, sem-unverified, compare-call, ...)
Writes DIR/candidates.tsv and DIR/admitted_<id>.tsv (id: D2, or D2_<kind>_<kind>... with ':' as '-'), and prints counts.
"""
import argparse
import hashlib
import itertools
import os
import re
import subprocess
import sys

COLS = ["layer", "function", "column", "data_file", "data_sha256", "data_line", "named_by", "kind"]


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def blocks(rel):
    out, cur = {}, None
    for line in open(rel, encoding="utf-8"):
        m = re.match(r"  ([AB]\d+) ", line)
        if m:
            cur = m.group(1)
            out[cur] = [line]
            continue
        if cur and line.startswith("      "):
            out[cur].append(line)
        elif not line.startswith("    "):
            cur = None
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--kairos", required=True)
    ap.add_argument("--kzdump", required=True)
    ap.add_argument("plans", nargs="+")
    a = ap.parse_args()
    if os.path.exists(a.out):
        sys.stderr.write("candidates.py: %s exists\n" % a.out)
        return 2
    os.makedirs(a.out)
    p0src = os.path.join(a.kairos, "lib/llvm/p0.cpp")
    p0lines = open(p0src, encoding="utf-8").read().split("\n")
    named = {}      # (layer, function, column or None) -> set(named_by)
    sem = {}        # (layer, function, column) -> source text of its unverified SEMANTICS record (one build's set)
    sems = []       # the unverified sets of the builds, which must be equal
    fam = {}        # P0 function -> family
    plan_lines = []
    for spec in a.plans:
        pdir, rel, facts = spec.split(":")
        side = os.path.join(pdir, "plan.side")
        plan_lines.append("plan %s %s" % (sha(side), side))
        rows = []
        for line in open(side, encoding="utf-8"):
            if line.startswith("row ") and (" state=planned" in line or " control-state=planned" in line):
                f = line.split()
                rows.append((f[1], f[2]))
            m = re.match(r"namespace-entry row=([0-9a-f]{16}) (.*)$", line)
            if m and m.group(1) in {k for k, _ in rows} | {l.split()[1] for l in open(side, encoding="utf-8") if l.startswith("row ") and (" state=planned" in l or " control-state=planned" in l)}:
                for fld in ("compare-call", "copy-call", "length-call", "fill-call"):
                    mm = re.search(r"\b%s=(\S+)" % fld, m.group(2))
                    if mm and mm.group(1) != "-":
                        for x in mm.group(1).split(","):
                            named.setdefault(("P0", x.split("@")[0], None), set()).add(fld)
        bl = blocks(rel)
        for key, label in rows:
            for line in bl.get(label, []):
                for m in re.finditer(r"P0-unverified\(([^)]*)\)", line):
                    for f in m.group(1).split(","):
                        if f.strip():
                            named.setdefault(("P0", f.strip(), None), set()).add("P0-unverified")
                for m in re.finditer(r"sem-unverified\(([^)]*)\)", line):
                    for f in m.group(1).split(","):
                        f = f.strip()
                        if ":" in f:
                            api, col = f.split(":", 1)
                            named.setdefault(("framework", api, col), set()).add("sem-unverified")
        r = subprocess.run([a.kzdump, facts], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        one = {}
        for line in r.stdout.decode("utf-8", "replace").split("\n"):
            m = re.match(r'\s*SEMANTICS\[\d+\] .*layer=(\S+) column=(\S+) verify=(\S+) .*api="([^"]+)".*source="([^"]*)"', line)
            if m and m.group(3) == "unverified":
                one[(m.group(1), m.group(4), m.group(2))] = m.group(5)
            m = re.match(r'\s*P0_TABLE\[\d+\] .*name="([^"]+)" family="([^"]+)"', line)
            if m:
                fam[m.group(1)] = m.group(2)
        sems.append(one)
    for one in sems[1:]:
        if set(one) != set(sems[0]):
            sys.stderr.write("candidates.py: the unverified entries of the builds differ: %s\n" % sorted(set(one) ^ set(sems[0]))[:5])
            return 1
    sem = {k: ("unverified", v) for k, v in sems[0].items()}
    lines = {}
    for (layer, fn, col), by in sorted(named.items(), key=lambda kv: (kv[0][0], kv[0][1], kv[0][2] or "")):
        for (sl, sf, sc), (ver, src) in sorted(sem.items()):
            if sl != layer or sf != fn or ver != "unverified" or (col is not None and sc != col):
                continue
            if layer == "P0":
                ln = next((i + 1 for i, t in enumerate(p0lines) if re.search(r'"%s"' % re.escape(fn), t)), 0)
                cm = re.search(r'\{"%s", "([^"]+)"' % re.escape(fn), p0lines[ln - 1]) if ln else None
                family = fam.get(fn) or (cm.group(1) if cm else "unknown")
                kind, dfile, dsha, dline = family.replace(" ", "-"), "kairos/lib/llvm/p0.cpp", sha(p0src), str(ln)
            else:
                m = re.search(r"\((framework_semantics_[^,]+\.txt),", src)
                dpath = os.path.join(a.kairos, "semantics", m.group(1)) if m else None
                dl = next((i + 1 for i, t in enumerate(open(dpath, encoding="utf-8")) if t.startswith("api %s " % fn)), 0) if dpath else 0
                kind, dfile, dsha, dline = "framework:%s" % sc, "kairos/semantics/%s" % m.group(1) if m else "-", sha(dpath) if dpath else "-", str(dl)
            k = (layer, fn, sc)
            if k in lines:
                lines[k][6] = ",".join(sorted(set(lines[k][6].split(",")) | by))
            else:
                lines[k] = [layer, fn, sc, dfile, dsha, dline, ",".join(sorted(by)), kind]
    rows = [lines[k] for k in sorted(lines)]
    kinds = {}
    for r in rows:
        kinds[r[7]] = kinds.get(r[7], 0) + 1
    head = ["kz-candidates 1", "rule judgement rules 8.13 item 3 (2026-11-18)"] + plan_lines + ["columns " + "\t".join(COLS)]
    body = ["\t".join(r) for r in rows]
    tail = "lines %d kinds %d: %s" % (len(rows), len(kinds), "; ".join("%s %d" % kv for kv in sorted(kinds.items())))
    cpath = os.path.join(a.out, "candidates.tsv")
    open(cpath, "w", encoding="utf-8").write("\n".join(head + body + [tail, "end"]) + "\n")
    csha = sha(cpath)
    ks = sorted(kinds)
    subsets = [tuple(ks)] + [c for n in range(1, len(ks)) for c in itertools.combinations(ks, n)]
    for sub in subsets:
        branch = "D2" if sub == tuple(ks) else "D2[%s]" % ",".join(sub)
        ident = "D2" if sub == tuple(ks) else "D2_" + "_".join(x.replace(":", "-") for x in sub)
        mine = [b for b, r in zip(body, rows) if r[7] in sub]
        txt = ["kz-admitted 1", "candidates %s" % csha, "branch %s" % branch]
        txt += ["ground %s: none: evaluation branch written before the PI's answer" % k for k in sub]
        txt += ["columns " + "\t".join(COLS)] + mine + ["lines %d" % len(mine), "end"]
        open(os.path.join(a.out, "admitted_%s.tsv" % ident), "w", encoding="utf-8").write("\n".join(txt) + "\n")
    print("candidates: %d lines, %d kinds (%s); admission files %d (D2 and %d partial)" % (len(rows), len(kinds), tail, len(subsets), len(subsets) - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())

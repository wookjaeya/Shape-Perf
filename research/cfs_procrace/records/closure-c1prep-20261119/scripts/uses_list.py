#!/usr/bin/env python3
"""uses_list.py -- the list of pre-defined uses of one C1 plan (evaluation protocol plan/c1_closure_evaluation_protocol_20261118.md
5.1; results 25.8), generated by rule from the plan and the relations text it was generated from.  Run with python3 -I.

    uses_list.py --build NAME --plan PLAN.kzs --sidecar PLAN.side --relations RELATIONS.txt -o OUT.tsv

Rule (no row id, key, name or expected value is an input):
  rows      the sidecar's row lines of path A (relations label A<n>) that the plan holds: state=planned (a tier) or
            control-state=planned (the path A control selection)
  consumer  each actor root of the row's "actors: {<root> (<kind>), ...}" line in the relations text (the roots the
            row's use is reached from); a row without that line has the consumer "none"
  use       each distinct use call of the row: the plan's sites with the rule name use-call whose row= names the row,
            an at-call and an after-call of one call (same tu, line, col, callee) taken as one use
  context   each sidecar "context row=<key> id=<n> frame=<at>,<after>" line of the row (the frame site ids), or "-" when
            the row has no context line (one context)
One line per (row, consumer, use, context).  Columns: build, row_label, row_key, path, consumer_root, use_tu, use_line,
use_col, callee, at_site, after_site, context_id, frame_sites, plan_state.  The tail line counts the lines.
"""
import argparse
import re
import sys


def main():
    ap = argparse.ArgumentParser()
    for o in ('--build', '--plan', '--sidecar', '--relations', '-o'):
        ap.add_argument(o, required=True)
    a = ap.parse_args()
    rows = []
    ctx = {}
    for line in open(a.sidecar, encoding='utf-8'):
        if line.startswith('row '):
            f = line.split()
            key, label = f[1], f[2]
            st = 'tier' if ' state=planned' in line else ''
            cs = 'control' if ' control-state=planned' in line else ''
            if label.startswith('A') and (st or cs):
                rows.append((key, label, '+'.join(x for x in (st, cs) if x)))
        m = re.match(r'context row=([0-9a-f]{16}) id=(\d+) frame=(\S+)', line)
        if m:
            ctx.setdefault(m.group(1), []).append((m.group(2), m.group(3)))
    actors = {}
    cur = None
    for line in open(a.relations, encoding='utf-8'):
        m = re.match(r'  (A\d+) ', line)
        if m:
            cur = m.group(1)
            continue
        if cur and line.startswith('      actors: {'):
            body = line.split('{', 1)[1].split('}', 1)[0]
            actors.setdefault(cur, [r.strip() for r in re.split(r', (?=[^,]+ \()', body) if r.strip()])
        if line.strip() == '' or (line.startswith('  ') and not line.startswith('    ')):
            pass
    sites = []
    for line in open(a.plan, encoding='utf-8'):
        if not line.startswith('site '):
            continue
        g = lambda k: (re.search(r'\b%s=("[^"]*"|\S+)' % k, line) or [None, ''])[1]
        rules = g('label').split('.', 1)[1] if '.' in g('label') else ''
        if 'use-call' not in rules.split('+'):
            continue
        sites.append({'id': int(line.split()[1]), 'rows': g('row').split(','), 'tu': g('tu'), 'line': g('line'), 'col': g('col'),
                      'callee': g('callee'), 'place': g('place')})
    out = []
    for key, label, state in rows:
        uses = {}
        for s in sites:
            if key in s['rows']:
                u = uses.setdefault((s['tu'], s['line'], s['col'], s['callee']), {'at': '-', 'after': '-'})
                u['at' if s['place'] == 'at-call' else 'after'] = str(s['id'])
        cons = actors.get(label) or ['none']
        cl = ctx.get(key) or [('-', '-')]
        for c in cons:
            for (tu, ln, col, callee), u in sorted(uses.items(), key=lambda kv: (kv[0][0], int(kv[0][1] or 0), kv[0][2])):
                for cid, fr in cl:
                    out.append([a.build, label, key, 'A', c, tu, ln, col or '-', callee, u['at'], u['after'], cid, fr, state])
    with open(a.o, 'w', encoding='utf-8') as o:
        o.write('kz-uses 1\n')
        o.write('rule evaluation protocol 5.1 (2026-11-18): planned path A rows x consumer roots x use calls x contexts\n')
        o.write('columns build\trow_label\trow_key\tpath\tconsumer_root\tuse_tu\tuse_line\tuse_col\tcallee\tat_site\tafter_site\tcontext_id\tframe_sites\tplan_state\n')
        for r in out:
            o.write('\t'.join(r) + '\n')
        o.write('lines %d rows %d\n' % (len(out), len({r[2] for r in out})))
        o.write('end\n')
    print('%s: %d uses over %d rows' % (a.build, len(out), len({r[2] for r in out})))
    return 0


if __name__ == '__main__':
    sys.exit(main())

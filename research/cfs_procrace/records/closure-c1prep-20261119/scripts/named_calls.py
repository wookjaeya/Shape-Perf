#!/usr/bin/env python3
"""named_calls.py -- the library calls the two C1 plans' name-space lines name, with their records in the facts
(judgement rules 8.14 item 5; plan/c1_closure_explain_rev4_spec_20261118.md 11 item 2, format kz-named-calls 1).
Generated by rule from the same inputs as candidates.py (the plans, and the facts each plan was generated from); no
line is chosen by hand.  It does not change candidates.py, the candidate list or the admission files.  Run with python3 -I.

    named_calls.py --out FILE --kzdump KZ_DUMP  PLAN_DIR:FACTS_KZ ...

Rule:
  rows      the sidecar's row lines the plan holds (state=planned or control-state=planned)
  named     every library call that a planned row's namespace-entry line, or the namespace-layer line of that entry's
            data file, names in compare-call=, copy-call=, length-call=, fill-call= (the text before '@')
  records   the facts' P0_TABLE records with that name plus its SEMANTICS records with that api, every column
            (kz-dump of the facts the plan was generated from)
  unverified  of those SEMANTICS records, the ones with verify=unverified
  layers    the layers that have a record: P0 for a P0_TABLE record, the SEMANTICS record's layer=; '-' when none
A call with records 0 has no entry: the judgement part holds nothing that rests on it in any data branch.  The counts
of the plans must be equal, else the script stops (rc 1) and writes nothing (as the candidate list's rule).
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys

FIELDS = ("compare-call", "copy-call", "length-call", "fill-call")
KV = re.compile(r'(\w[\w-]*)=("(?:[^"\\]|\\.)*"|\S+)')


def sha(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--kzdump", required=True)
    ap.add_argument("plans", nargs="+")
    a = ap.parse_args()
    if os.path.exists(a.out):
        sys.stderr.write("named_calls.py: %s exists\n" % a.out)
        return 2
    heads, facts_lines, per = [], [], []
    for spec in a.plans:
        pdir, facts = spec.split(":")
        side = os.path.join(pdir, "plan.side")
        heads.append("plan %s %s" % (sha(side), side))
        facts_lines.append("facts %s %s" % (sha(facts), facts))
        with open(side, encoding="utf-8") as f:
            lines = f.read().split("\n")
        planned = {ln.split()[1] for ln in lines if ln.startswith("row ") and (" state=planned" in ln or " control-state=planned" in ln)}
        ents = [dict(KV.findall(ln)) for ln in lines if ln.startswith("namespace-entry ")]
        ents = [e for e in ents if e.get("row") in planned]
        datas = {e.get("data") for e in ents}
        lays = [dict(KV.findall(ln)) for ln in lines if ln.startswith("namespace-layer ")]
        lays = [x for x in lays if x.get("data") in datas]
        named = {}
        for d in ents + lays:
            for fld in FIELDS:
                for x in d.get(fld, "-").split(","):
                    if x and x != "-":
                        named.setdefault(x.split("@")[0], set()).add(fld)
        r = subprocess.run([a.kzdump, facts], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        if r.returncode != 0:
            sys.stderr.write("named_calls.py: kz-dump %s rc %d\n" % (facts, r.returncode))
            return 1
        rec = {fn: {"records": 0, "unverified": 0, "layers": set()} for fn in named}
        for line in r.stdout.decode("utf-8", "replace").split("\n"):
            m = re.match(r'\s*P0_TABLE\[\d+\] .*\bname="([^"]+)"', line)
            if m and m.group(1) in rec:
                rec[m.group(1)]["records"] += 1
                rec[m.group(1)]["layers"].add("P0")
                continue
            m = re.match(r'\s*SEMANTICS\[\d+\] .*\blayer=(\S+) column=(\S+) verify=(\S+) .*\bapi="([^"]+)"', line)
            if m and m.group(4) in rec:
                x = rec[m.group(4)]
                x["records"] += 1
                x["layers"].add(m.group(1))
                if m.group(3) == "unverified":
                    x["unverified"] += 1
        per.append({fn: (",".join(sorted(named[fn])), rec[fn]["records"], rec[fn]["unverified"],
                         ",".join(sorted(rec[fn]["layers"])) or "-") for fn in named})
    for one in per[1:]:
        if one != per[0]:
            diff = sorted(set(one.items()) ^ set(per[0].items()))[:5]
            sys.stderr.write("named_calls.py: the plans differ: %s\n" % (diff,))
            return 1
    rows = ["%s\t%s\t%d\t%d\t%s" % ((fn,) + per[0][fn]) for fn in sorted(per[0])]
    noent = sum(1 for fn in per[0] if per[0][fn][1] == 0)
    txt = (["kz-named-calls 1", "rule judgement rules 8.14 item 5 (2026-11-19): every library call that a planned row's "
            "namespace-entry or namespace-layer line names, with its records in the facts"] + heads + facts_lines +
           ["columns function\tnamed_by\trecords\tunverified\tlayers"] + rows + ["lines %d no_entry %d" % (len(rows), noent), "end"])
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(txt) + "\n")
    print("named calls: %d, no entry %d: %s" % (len(rows), noent, "; ".join(r.replace("\t", " ") for r in rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
